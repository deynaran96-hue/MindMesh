"""
General helper functions for session state, formatting, and file export.
"""

import json
from typing import Dict, Any, List

def init_session_state(st):
    """Initialize all Streamlit session state variables if they do not exist."""
    defaults = {
        "current_page": "Dashboard",
        "study_material": "",
        "active_topic": "Operating Systems",
        "material_source": "Empty",
        "summary_data": None,
        "mcq_data": None,
        "quiz_score": None,
        "quiz_submitted": False,
        "user_answers": {},
        "flashcards_data": None,
        "flashcard_index": 0,
        "flashcard_flipped": False,
        "mastered_cards": set(),
        "chat_history": [],
        "exam_questions_data": None,
        "revision_plan_data": None,
        "ai_provider": "local_engine",  # 'ollama', 'api', or 'local_engine'
        "ollama_url": "http://localhost:11434",
        "ollama_model": "gemma:2b",
        "api_key": "",
        "api_endpoint": "https://api.groq.com/openai/v1/chat/completions",
        "api_model": "gemma2-9b-it"
    }

    for key, value in defaults.items():
        if key not in st.session_state:
            st.session_state[key] = value

def export_as_markdown(title: str, content: str) -> str:
    """Format content as downloadable markdown."""
    return f"# {title}\n*Generated by MindMesh AI (Gemma Powered)*\n\n{content}"

def export_as_json(data: Any) -> str:
    """Format data as downloadable JSON."""
    return json.dumps(data, indent=2, ensure_ascii=False)
